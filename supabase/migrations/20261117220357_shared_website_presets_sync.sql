insert into public.shared_website_presets (label, website_url, category, added_from)
select
  left(coalesce(nullif(regexp_replace(split_part(regexp_replace(r.website_url, '^https?://', '', 'i'), '/', 1), '^www\.', '', 'i'), ''), r.website_url), 80),
  r.website_url,
  case r.section
    when '🎮 Games' then 'Games'
    when '🎬 Movies & Misc' then 'Movies & Misc'
    when '🔗 Proxies' then 'Proxies'
    else r.section
  end,
  'website-load-recommendation'
from public.website_recommendations r
where r.status = 'added'
  and r.section in ('🎮 Games','🎬 Movies & Misc','🔗 Proxies','My own creations!','Working Proxies','Scratch')
on conflict (website_url) do nothing;

create or replace function public.admin_accept_website_recommendation(
  p_recommendation_id bigint,
  p_section text
)
returns void
language plpgsql
security definer
set search_path to ''
as $function$
declare
  target_url text;
  target_label text;
  target_category text;
begin
  if auth.uid() is null or not private.is_admin() then
    raise exception 'admin access required' using errcode = '42501';
  end if;
  if p_section not in (
    '🎮 Games','🎬 Movies & Misc','🔗 Proxies',
    'My own creations!','Working Proxies','Scratch'
  ) then
    raise exception 'invalid recommendation section';
  end if;

  select website_url into target_url
  from public.website_recommendations
  where id = p_recommendation_id and status <> 'declined'
  for update;

  if not found then
    raise exception 'recommendation not found or declined';
  end if;

  target_category := case p_section
    when '🎮 Games' then 'Games'
    when '🎬 Movies & Misc' then 'Movies & Misc'
    when '🔗 Proxies' then 'Proxies'
    else p_section
  end;

  target_label := left(
    regexp_replace(
      split_part(regexp_replace(target_url, '^https?://', '', 'i'), '/', 1),
      '^www\.', '', 'i'
    ),
    80
  );

  insert into public.shared_website_presets
    (label, website_url, category, created_by, added_from, is_active)
  values (target_label, target_url, target_category, auth.uid(), 'website-load-recommendation', true)
  on conflict (website_url) do update
    set is_active = true, category = excluded.category, updated_at = now();

  update public.website_recommendations
  set status = 'added', section = p_section
  where id = p_recommendation_id;
end;
$function$;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'shared_website_presets'
  ) then
    alter publication supabase_realtime add table public.shared_website_presets;
  end if;
end
$$;
