-- Shared preset catalogue for Proxy and Website Load.
-- Both GitHub Pages sites use the same Supabase project; Realtime keeps their lists in sync.

create table public.shared_website_presets (
  id bigint generated by default as identity primary key,
  label text not null check (char_length(btrim(label)) between 1 and 80),
  website_url text not null unique check (
    char_length(website_url) between 8 and 500
    and website_url ~* '^https?://'
  ),
  category text not null check (
    category in ('Games','Study','Movies & Misc','Proxies','My own creations!','Working Proxies','Scratch')
  ),
  created_by uuid references auth.users(id) on delete set null,
  added_from text not null default 'website-load'
    check (added_from in ('seed','proxy','website-load-recommendation')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index shared_website_presets_category_label_idx
  on public.shared_website_presets (category, lower(label));

alter table public.shared_website_presets enable row level security;

grant select on public.shared_website_presets to anon, authenticated;
grant insert, update, delete on public.shared_website_presets to authenticated;
grant usage, select on sequence public.shared_website_presets_id_seq to authenticated;
grant usage on schema private to authenticated;
grant execute on function private.is_admin() to authenticated;

create policy "Shared website presets are publicly readable"
  on public.shared_website_presets for select to anon, authenticated
  using (is_active = true);

create policy "Only active admins can add shared website presets"
  on public.shared_website_presets for insert to authenticated
  with check ((select private.is_admin()) and created_by = (select auth.uid()));

create policy "Only active admins can update shared website presets"
  on public.shared_website_presets for update to authenticated
  using ((select private.is_admin()))
  with check ((select private.is_admin()));

create policy "Only active admins can remove shared website presets"
  on public.shared_website_presets for delete to authenticated
  using ((select private.is_admin()));

